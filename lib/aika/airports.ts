/** List of domestic Indian airport codes */
export const domesticCodes = Object.keys(airports).filter(
    code => airports[code].country === 'IN'
);

/** Checks whether an airport is in India based on country metadata */
export function isDomesticIndianAirport(code: string): boolean {
    if (!code || !airports[code]) return false;
    return airports[code].country === 'IN';
}

/** Get time zone of an airport */
export function getAirportTimezone(code: string): string | undefined {
    return airports[code]?.zone;
}

/**
 * Searches and prioritizes airports based on query string:
 * 1. Exact IATA or ICAO code match
 * 2. IATA or ICAO starts with query
 * 3. Exact city match
 * 4. City starts with query
 * 5. Name starts with query
 * 6. Word in city starts with query
 * 7. Word in name starts with query
 * 8. City substring match
 * 9. Name substring match
 */
export function searchAirports(
    query: string,
    domesticOnly = false
): [string, AirportRecord][] {
    const q = query.trim().toLowerCase();
    const entries = Object.entries(airports).filter(([, a]) => {
        if (domesticOnly && a.country !== 'IN') return false;
        return true;
    });

    if (!q) {
        return entries;
    }

    type ScoredEntry = {
        code: string;
        airport: AirportRecord;
        score: number;
    };

    const scored: ScoredEntry[] = [];

    for (const [code, a] of entries) {
        const codeLower = code.toLowerCase();
        const icaoLower = (a.icao || '').toLowerCase();
        const cityLower = (a.city || '').toLowerCase();
        const nameLower = a.name.toLowerCase();

        let score = -1;

        if (codeLower === q) {
            score = 0;
        } else if (icaoLower === q) {
            score = 1;
        } else if (codeLower.startsWith(q)) {
            score = 2;
        } else if (icaoLower.startsWith(q)) {
            score = 3;
        } else if (cityLower === q) {
            score = 4;
        } else if (cityLower.startsWith(q)) {
            score = 5;
        } else if (nameLower.startsWith(q)) {
            score = 6;
        } else if (cityLower.split(/\s+/).some(w => w.startsWith(q))) {
            score = 7;
        } else if (nameLower.split(/\s+/).some(w => w.startsWith(q))) {
            score = 8;
        } else if (cityLower.includes(q)) {
            score = 9;
        } else if (nameLower.includes(q)) {
            score = 10;
        }

        if (score !== -1) {
            scored.push({ code, airport: a, score });
        }
    }

    scored.sort((a, b) => {
        if (a.score !== b.score) return a.score - b.score;
        return a.code.localeCompare(b.code);
    });

    return scored.map(s => [s.code, s.airport]);
}
